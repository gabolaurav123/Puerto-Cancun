const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require(require.resolve('playwright', { paths: [process.env.PLAYWRIGHT_MODULES || process.cwd()] }));

const base = process.env.PCC_TEST_BASE;
if (!base || !['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Use a disposable local QA server via PCC_TEST_BASE.');
const output = path.resolve(process.env.PCC_QA_OUTPUT || 'tmp/account-editor-qa');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.PCC_CHROME_PATH ? { executablePath: process.env.PCC_CHROME_PATH } : {}) });
  const errors = [];
  let page;
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, extraHTTPHeaders: { 'X-Forwarded-For': '127.0.0.91' } });
    page = await context.newPage();
    page.setDefaultTimeout(12000);
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/panel`);
    await page.locator('#loginForm [name=username]').fill(process.env.PCC_TEST_ADMIN || 'qa-admin');
    await page.locator('#loginForm [name=password]').fill(process.env.PCC_TEST_PASSWORD || 'qa-admin-password-only-local');
    await page.locator('#loginForm button[type=submit]').click();
    await page.waitForSelector('#adminPanel:not([hidden])');
    if (await page.getByRole('button', { name: 'Solo esenciales', exact: true }).isVisible()) await page.getByRole('button', { name: 'Solo esenciales', exact: true }).click();
    const select = async (section, child) => {
      if (page.viewportSize().width <= 980 && await page.locator('#adminPanel').evaluate(el => el.classList.contains('sidebar-collapsed'))) await page.locator('#adminSidebarToggle').click();
      await page.locator(`[data-admin-section="${section}"]`).click();
      if (child) await page.locator(`.admin-sidebar-subnav [data-admin-section-link="${child}"]`).click();
    };
    let csrfFailures = 0;
    await page.route('**/api/admin/listing-drafts/new-properties', route => {
      if (route.request().method() === 'PUT' && csrfFailures++ === 0) return route.fulfill({ status: 403, contentType: 'application/json', body: JSON.stringify({ code: 'CSRF_INVALID', error: 'QA token expired' }) });
      return route.continue();
    });
    await select('properties', 'new-property');
    const title = page.locator('#listingForm [name=title]');
    const description = page.locator('#listingForm [name=description]');
    await title.fill('QA borrador vivienda');
    await description.fill('Casa con dos recámaras y terraza.');
    await select('developments', 'new-development');
    await title.fill('QA borrador desarrollo');
    await page.waitForFunction(() => document.querySelector('#listingDraftStatus').textContent.includes('sincronizado'));
    await select('properties');
    await page.locator('[data-open-listing-draft="new-properties"]').click();
    await page.waitForFunction(() => document.querySelector('#listingForm [name=title]').value === 'QA borrador vivienda');
    assert.equal(await description.inputValue(), 'Casa con dos recámaras y terraza.');
    await page.locator('[data-improve-description="description"]').click();
    await page.waitForFunction(() => document.querySelector('#listingAiMessage').textContent.includes('original'));
    assert.equal(await description.inputValue(), 'Casa con dos recámaras y terraza.');
    // Isolate the paid provider: exercise review/apply without spending credits.
    await page.route('**/api/admin/ai/improve-description', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ description: 'Casa con terraza y dos recámaras.' }) }));
    await page.locator('[data-improve-description="description"]').click();
    await page.locator('#listingAiReview').waitFor({ state: 'visible' });
    await description.fill('Texto editado mientras se revisa la propuesta.');
    await page.locator('#applyListingAi').click();
    assert.equal(await description.inputValue(), 'Texto editado mientras se revisa la propuesta.');
    await page.locator('#discardListingAi').click();
    await description.fill('Casa con dos recámaras y terraza.');
    await page.locator('[data-improve-description="description"]').click();
    await page.locator('#applyListingAi').click();
    assert.equal(await description.inputValue(), 'Casa con terraza y dos recámaras.');
    await page.waitForFunction(() => document.querySelector('#listingDraftStatus').textContent.includes('sincronizado'));
    await page.reload();
    await page.waitForSelector('#adminPanel:not([hidden])');
    await select('properties');
    await page.locator('[data-open-listing-draft="new-properties"]').click();
    await page.waitForFunction(() => document.querySelector('#listingForm [name=title]').value === 'QA borrador vivienda');
    assert.equal(await description.inputValue(), 'Casa con terraza y dos recámaras.');
    await page.screenshot({ path: path.join(output, 'desktop-editor.png') });
    console.log('PASS: separate drafts, navigation, reload, inline AI failure/review/apply');
    assert.ok(csrfFailures >= 2, 'Expired security token must be retried without losing the form');
    await select('properties');
    await page.locator('#adminListings [data-edit-listing]').first().click();
    await description.fill('QA cambios pendientes en una publicación existente.');
    await select('properties', 'new-property');
    await page.waitForFunction(() => document.querySelector('#listingForm [name=title]').value === 'QA borrador vivienda');
    console.log('PASS: starting a new listing preserves the separate existing-record draft');
    await select('properties');
    for (const sort of ['created_desc', 'created_asc', 'updated_desc', 'title_asc', 'price_asc', 'price_desc']) await page.locator('#adminListingSort').selectOption(sort);
    await select('roles');
    await page.locator('#adminUserSource').selectOption('registered');
    assert.ok(await page.locator('#adminRoles tbody tr').count() > 0);
    await page.locator('#adminUserSource').selectOption('');
    await page.locator('#toggleUserForm').click();
    const staffEmail = `qa-ui-staff-${Date.now()}@example.test`;
    await page.locator('#internalUserForm [name=name]').fill('QA Equipo');
    await page.locator('#internalUserForm [name=email]').fill(staffEmail);
    await page.locator('#internalUserForm [name=password]').fill('editor');
    await page.locator('#internalUserForm [name=role]').selectOption('editor');
    await page.locator('#internalUserForm button[type=submit]').click();
    await page.locator('#internalUserForm').waitFor({ state: 'hidden' });
    await page.locator('#adminUserSearch').fill(staffEmail);
    await page.locator('#adminRoles [data-edit-user]').click();
    await page.locator('#internalUserForm [name=password]').fill('654321');
    await page.locator('#internalUserForm [name=role]').selectOption('viewer');
    await page.locator('#internalUserForm button[type=submit]').click();
    await page.locator('#internalUserForm').waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.querySelector('#adminRoles').textContent.includes('Solo lectura'));
    assert.match(await page.locator('#adminRoles').innerText(), /Solo lectura/);
    await page.screenshot({ path: path.join(output, 'desktop-users.png') });
    console.log('PASS: inventory sort controls, account filters, creation, password reset and role edit');
    await page.setViewportSize({ width: 390, height: 844 });
    await select('developments', 'new-development');
    assert.ok(await page.locator('#adminPanel').evaluate(el => el.classList.contains('sidebar-collapsed')));
    await title.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, 'mobile-editor.png') });
    await page.locator('#listingSubmitButton').scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, 'mobile-editor-actions.png') });
    console.log('PASS: mobile menu, fields, save button and no horizontal overflow');

    const customerContext = await browser.newContext({ viewport: { width: 390, height: 844 }, extraHTTPHeaders: { 'X-Forwarded-For': '127.0.0.92' } });
    page = await customerContext.newPage();
    page.setDefaultTimeout(12000);
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/?auth=login`);
    // Consent is optional; dismiss it before the deliberately long mobile form.
    if (await page.getByRole('button', { name: 'Solo esenciales', exact: true }).isVisible()) await page.getByRole('button', { name: 'Solo esenciales', exact: true }).click({ force: true });
    await page.locator('#loginForm [name=username]').fill('unknown@example.test');
    await page.locator('#loginForm [name=password]').fill('123456');
    await page.locator('#loginForm button[type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#loginMessage').textContent.length > 0);
    assert.ok(await page.locator('#authModal').isVisible());
    assert.ok(await page.locator('#loginForm').isVisible());
    assert.equal(await page.locator('#loginForm [name=username]').inputValue(), 'unknown@example.test');
    await page.locator('.modal-tabs [data-auth-tab=register]').click();
    const email = `qa-ui-client-${Date.now()}@example.test`;
    const rf = page.locator('#registerForm');
    await rf.locator('[name=firstName]').fill('Prueba');
    await rf.locator('[name=lastName]').fill('Movil');
    await rf.locator('[name=email]').fill(email);
    await rf.locator('[name=phone]').fill('9981234567');
    await rf.locator('[name=password]').fill('123456');
    await rf.locator('[name=confirmPassword]').fill('654321');
    await rf.locator('[name=consent]').check();
    await rf.locator('button[type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#registerMessage').textContent.includes('coincide'));
    assert.ok(await rf.isVisible());
    assert.equal(await rf.locator('[name=email]').inputValue(), email);
    await page.screenshot({ path: path.join(output, 'mobile-register-error.png') });
    await rf.locator('[name=confirmPassword]').fill('123456');
    await rf.locator('button[type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#registerMessage').textContent.includes('Cuenta creada'));
    console.log('PASS: failed login/registration preserve forms; six-character registration accepted');
    await page.locator('.modal-tabs [data-auth-tab=login]').click();
    await page.locator('#loginForm [name=username]').fill(email);
    await page.locator('#loginForm [name=password]').fill('123456');
    await page.locator('#loginForm button[type=submit]').click();
    await page.waitForSelector('#sellerPanel:not([hidden])');
    await page.locator('#accountPasswordButton').click();
    await page.locator('#passwordUpdateForm [name=currentPassword]').fill('123456');
    await page.locator('#passwordUpdateForm [name=newPassword]').fill('abcdef');
    await page.locator('#passwordUpdateForm [name=confirmNewPassword]').fill('abcdef');
    await page.locator('#passwordUpdateForm button[type=submit]').click();
    await page.locator('#authModal').waitFor({ state: 'hidden' });
    const session = await page.evaluate(() => fetch('/api/session').then(r => r.json()));
    assert.equal(session.user.email, email);
    assert.equal(session.user.role, 'seller');
    assert.deepEqual(errors, []);
    console.log('PASS: signed-in customer changes password and stays signed in; no page exceptions');
    fs.writeFileSync(path.join(output, 'browser-result.json'), JSON.stringify({ passed: true, errors, checkedAt: new Date().toISOString() }, null, 2));
  } catch (error) {
    if (page) await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => null);
    console.error(error);
    process.exitCode = 1;
  } finally { await browser.close(); }
})();
