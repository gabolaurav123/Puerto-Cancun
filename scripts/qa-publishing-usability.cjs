const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const { chromium } = require(require.resolve('playwright', { paths: [process.env.PLAYWRIGHT_MODULES || process.cwd()] }));
const base = process.env.PCC_TEST_BASE;
if (!base || !['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Disposable local server required.');
const output = path.resolve(process.env.PCC_QA_OUTPUT || 'tmp/publishing-qa');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PCC_CHROME_PATH });
  let page;
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, extraHTTPHeaders: { 'X-Forwarded-For': '127.0.0.125' } });
    page = await context.newPage();
    page.setDefaultTimeout(15000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.goto(base + '/panel');
    await page.locator('#loginForm [name=username]').fill('qa-admin');
    await page.locator('#loginForm [name=password]').fill('qa-admin-password-only-local');
    await page.locator('#loginForm button[type=submit]').click();
    await page.waitForSelector('#adminPanel:not([hidden])');
    const consent = page.getByRole('button', { name: 'Solo esenciales', exact: true });
    if (await consent.isVisible()) await consent.click();
    const select = async (section, child) => {
      if (page.viewportSize().width <= 980 && await page.locator('#adminPanel').evaluate(el => el.classList.contains('sidebar-collapsed'))) await page.locator('#adminSidebarToggle').click();
      await page.locator(`[data-admin-section="${section}"]`).click();
      if (child) await page.locator(`.admin-sidebar-subnav [data-admin-section-link="${child}"]`).click();
    };
    await select('developments', 'new-development');
    const titleText = `QA Development ${Date.now()}`;
    const form = page.locator('#listingForm');
    const title = form.locator('[name=title]');
    const description = form.locator('[name=description]');
    await title.fill(titleText);
    await form.locator('[name=state]').fill('Quintana Roo');
    await form.locator('[name=city]').fill('Cancun');
    await form.locator('[name=zone]').fill('Puerto Cancun');
    await description.fill('Texto manual que debe conservarse.');
    assert.equal(await form.locator('[name=isPublic]').isVisible(), false);
    assert.equal(await form.locator('[name=featured]').isVisible(), false);
    assert.equal(await page.locator('[data-admin-section=prompts]').count(), 0);
    assert.equal(await page.locator('#listingResearchOption').isVisible(), true);
    const image = await sharp({ create: { width: 1000, height: 700, channels: 3, background: '#e7eeeb' } }).jpeg().toBuffer();
    await form.locator('[name=imageFile]').setInputFiles(Array.from({ length: 51 }, (_, index) => ({ name: `photo-${index}.jpg`, mimeType: 'image/jpeg', buffer: image })));
    await page.waitForFunction(() => document.querySelectorAll('#listingImagePreview .image-preview-item').length === 51);
    assert.equal(await page.locator('#operationStack').innerText(), '');
    const calls = [];
    let delayResolve;
    let delayDescription = false;
    let failDescription = false;
    await page.route('**/api/admin/ai/analyze-images', async route => {
      const body = route.request().postDataJSON();
      assert.ok(body.images.length <= 10);
      calls.push({ mode: body.mode, count: body.images.length });
      if (delayDescription && body.mode === 'description') await new Promise(resolve => { delayResolve = resolve; });
      await route.fulfill({ contentType: 'application/json', body: JSON.stringify({
        provider: failDescription && body.mode === 'description' ? 'technical' : 'openai', warning: failDescription ? 'Proveedor de prueba no disponible' : '',
        totalCount: body.images.length, analyzedCount: body.images.length,
        items: body.images.map((_, index) => ({ index, visualAnalyzed: true, classification: 'terraza', suggestedAlt: `Terraza ${index + 1}.`, suggestedAltEn: `Terrace ${index + 1}.`, coverScore: 90 - index })),
        keywords: ['terraza', 'luz natural', 'alberca'],
        descriptionEs: failDescription ? '' : 'Las fotografias muestran una terraza con luz natural.', descriptionEn: '', sources: [],
      }) });
    });
    await page.locator('#analyzeListingImages').click();
    await page.waitForFunction(() => document.querySelector('#listingImageAnalysisMessage').textContent.includes('51 de 51'));
    assert.deepEqual(calls.map(item => item.count), [10, 10, 10, 10, 10, 1]);
    assert.equal(await page.locator('[data-photo-caption-es]').count(), 51);
    assert.equal(await page.locator('#listingPhotoKeywords').isVisible(), false);
    await page.locator('#applyAllPhotoCaptions').click();
    assert.equal(await page.locator('#listingImagePreview [data-image-description=es]').last().inputValue(), 'Terraza 1.');
    await page.locator('#generateListingKeywords').click();
    await page.locator('#listingPhotoKeywords').waitFor({ state: 'visible' });
    await page.locator('[data-photo-keyword="2"]').uncheck();
    await page.locator('#applyPhotoKeywords').click();
    assert.equal(await page.locator('#listingKeywords').inputValue(), 'terraza, luz natural');
    await page.locator('[data-generate-photo-description=description]').click();
    await page.locator('#listingAiReview').waitFor({ state: 'visible' });
    assert.equal(await description.inputValue(), 'Texto manual que debe conservarse.');
    await page.locator('#applyListingAi').click();
    assert.match(await description.inputValue(), /fotografias muestran/);
    await form.locator('[name=titleEn]').fill('Manual English title');
    await page.route('**/api/admin/ai/translate-property', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ titleEn: 'Do not replace title', descriptionEn: 'The photos show a terrace with natural light.' }) }));
    await page.locator('#translateListingDescription').click();
    await page.waitForFunction(() => document.querySelector('#listingForm [name=descriptionEn]').value.includes('The photos'));
    assert.equal(await form.locator('[name=titleEn]').inputValue(), 'Manual English title');
    failDescription = true;
    await page.locator('[data-generate-photo-description=description]').click();
    await page.waitForFunction(() => document.querySelector('#listingAiMessage').textContent.includes('Proveedor de prueba'));
    assert.match(await description.inputValue(), /fotografias muestran/);
    failDescription = false;
    await page.locator('#saveListingProgress').click();
    await page.waitForFunction(() => document.querySelector('#listingQuickDraftStatus').textContent.includes('Puedes continuarlo'));
    await select('developments');
    await page.locator('[data-preview-listing-draft=new-developments]').click();
    await page.locator('#draftPreviewDialog').waitFor({ state: 'visible' });
    assert.match(await page.locator('#draftPreviewContent').innerText(), /fotografias muestran/);
    await page.locator('#draftPreviewDialog button').click();
    await page.reload();
    await page.waitForSelector('#adminPanel:not([hidden])');
    await select('developments');
    await page.locator('[data-open-listing-draft=new-developments]').click();
    await page.waitForFunction(() => document.querySelectorAll('#listingImagePreview .image-preview-item').length === 51);
    assert.equal(await title.inputValue(), titleText);
    assert.equal(await page.locator('#listingImagePreview [data-image-description=es]').last().inputValue(), 'Terraza 1.');
    await description.scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'desktop-description.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await description.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, 'mobile-description.png') });
    await page.locator('#listingSubmitButton').click();
    await page.locator('#listingPublishDialog').waitFor({ state: 'visible' });
    await page.screenshot({ path: path.join(output, 'mobile-publication-confirmation.png') });
    await page.locator('#listingPublishDialog [value=cancel]').click();
    assert.equal(await title.inputValue(), titleText);
    await page.locator('#listingSubmitButton').click();
    await page.locator('#listingPublishPrivate').check();
    const savedResponse = page.waitForResponse(response => response.url() === base + '/api/admin/properties' && response.request().method() === 'POST');
    await page.locator('#listingPublishDialog [value=save]').click();
    const saved = (await (await savedResponse).json()).property;
    assert.ok(saved, await page.locator('#listingFormMessage').innerText());
    assert.equal(saved.isPublic, false);
    assert.equal(saved.images.length, 51);
    await page.locator(`[data-edit-listing="${saved.id}"]`).waitFor({ state: 'visible' });
    await page.locator(`[data-edit-listing="${saved.id}"]`).click();
    await page.locator('#listingSubmitButton').click();
    await page.locator('#listingPublishPublic').check();
    const publishedResponse = page.waitForResponse(response => response.url().endsWith('/api/admin/properties/' + saved.id) && response.request().method() === 'PUT');
    await page.locator('#listingPublishDialog [value=save]').click();
    const published = (await (await publishedResponse).json()).property;
    assert.equal(published.isPublic, true);
    assert.equal(published.status, 'active');
    await page.locator(`[data-edit-listing="${saved.id}"]`).waitFor({ state: 'visible' });
    await select('roles');
    await page.locator('#toggleUserForm').click();
    await page.locator('.permission-grid').scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const permissionBoxes = await page.locator('.permission-grid input').evaluateAll(elements => elements.map(input => ({ w: input.getBoundingClientRect().width, h: input.getBoundingClientRect().height })));
    assert.ok(permissionBoxes.every(box => box.w >= 18 && box.w <= 24 && box.h >= 18 && box.h <= 24));
    await page.screenshot({ path: path.join(output, 'mobile-permissions.png') });
    await select('pdf');
    await page.locator('.pdf-checkbox').first().scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, 'mobile-pdf-options.png') });
    await page.goto(base + '/');
    await page.locator('.property-card').first().waitFor();
    await page.locator('.property-actions').first().scrollIntoViewIfNeeded();
    assert.match(await page.locator('.property-actions').first().innerText(), /Solicitar visita/);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(output, 'mobile-property-actions.png') });
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'browser-result.json'), JSON.stringify({ passed: true, calls, errors, propertyId: saved.id, provider: 'mocked', checkedAt: new Date().toISOString() }, null, 2));
    console.log('PASS: 51 captions, separate keyword/description/translation flows, provider failure, persistent private drafts, preview, publication modal, actual private/public saves, mobile controls, no page exceptions. Paid AI mocked.');
  } catch (error) {
    if (page) await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
    console.error(error);
    process.exitCode = 1;
  } finally { await browser.close(); }
})();
